"use client";

import { motion } from "framer-motion";
import { Shield, ChevronDown, ChevronUp, Copy, Check } from "lucide-react";
import { useState } from "react";

interface Props {
  report: string;
}

export default function AIReport({ report }: Props) {
  const [expanded, setExpanded] = useState(true);
  const [copied, setCopied] = useState(false);

  function copyReport() {
    navigator.clipboard.writeText(report);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }

  // The B2B report is emoji-formatted plain text — render it directly
  // with proper line-break handling rather than trying to parse sections.
  const lines = report.split("\n");

  return (    <div className="glass rounded-2xl border border-border p-6">
      <div className="flex items-center justify-between mb-6">
        <div className="flex items-center gap-2">
          <div className="w-8 h-8 rounded-lg bg-indigo/20 border border-indigo/30 flex items-center justify-center">
            <Shield size={14} className="text-indigo-glow" />
          </div>
          <div>
            <h2 className="font-display font-600 text-white text-sm">
              Wallet Health Report
            </h2>
            <p className="text-muted text-[10px] font-mono">
              Generated by TreasuryWizard AI · Groq Llama 3.1 70B
            </p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <button
            onClick={copyReport}
            className="flex items-center gap-1 text-xs text-muted hover:text-white transition-colors font-mono px-2 py-1 rounded border border-border hover:border-subtle"
            title="Copy report"
          >
            {copied ? <Check size={12} className="text-emerald" /> : <Copy size={12} />}
            {copied ? "Copied" : "Copy"}
          </button>
          <button
            onClick={() => setExpanded(!expanded)}
            className="text-muted hover:text-white transition-colors"
          >
            {expanded ? <ChevronUp size={16} /> : <ChevronDown size={16} />}
          </button>
        </div>
      </div>

      {expanded && (
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          className="rounded-xl border border-border bg-void/60 p-5"
        >
          <div className="space-y-1">
            {lines.map((line, i) => {
              // Section headers
              const isHeader = /^[🎯📊⚠️💡🧙]/.test(line.trim()) && line.includes("**");
              // Bullet points
              const isBullet = line.trim().startsWith("-") || line.trim().startsWith("•");
              // CTA line
              const isCTA = line.includes("AGENT") && line.includes("🧙");

              if (line.trim() === "") {
                return <div key={i} className="h-2" />;
              }

              if (isCTA) {
                return (
                  <div key={i} className="mt-4 p-4 rounded-xl bg-indigo/10 border border-indigo/30">
                    <p className="text-indigo-glow text-sm leading-relaxed font-body">
                      {line.replace(/\*\*/g, "")}
                    </p>
                  </div>
                );
              }

              if (isHeader) {
                return (
                  <p key={i} className="text-white font-display font-600 text-sm pt-3 first:pt-0">
                    {line.replace(/\*\*/g, "")}
                  </p>
                );
              }

              if (isBullet) {
                return (
                  <div key={i} className="flex gap-2 items-start pl-2">
                    <span className="text-indigo mt-1 shrink-0 text-xs">▸</span>
                    <span className="text-slate-300 text-sm leading-relaxed font-body">
                      {line.replace(/^[-•]\s*/, "").replace(/\*\*/g, "")}
                    </span>
                  </div>
                );
              }

              return (
                <p key={i} className="text-slate-300 text-sm leading-relaxed font-body">
                  {line.replace(/\*\*/g, "")}
                </p>
              );
            })}
          </div>
        </motion.div>
      )}
    </div>
  );
}
